import { strToU8, zipSync } from 'fflate';
import { ROLE_DEFS, snakeToCamel } from './roles';
import type { Scheme } from './engine';

export interface ExportKind {
  id: 'figma' | 'json' | 'kotlin' | 'css' | 'xml';
  label: string;
  extension: string;
  language: string;
}

export const EXPORT_KINDS: ExportKind[] = [
  { id: 'figma', label: 'Figma variables', extension: 'zip', language: 'json' },
  { id: 'kotlin', label: 'Kotlin', extension: 'kt', language: 'kotlin' },
  { id: 'json', label: 'JSON', extension: 'json', language: 'json' },
  { id: 'css', label: 'CSS', extension: 'css', language: 'css' },
  { id: 'xml', label: 'Android XML', extension: 'xml', language: 'xml' },
];

export function fileStem(scheme: Scheme): string {
  return `m3-spec${scheme.requestedSpec}-${scheme.seedHex.slice(1)}-${scheme.style}`;
}

export function serialize(scheme: Scheme, kind: ExportKind['id']): string {
  switch (kind) {
    case 'figma':
      return figmaBundleFiles(scheme)['light.tokens.json'];
    case 'json':
      return toJson(scheme);
    case 'kotlin':
      return toKotlin(scheme);
    case 'css':
      return toCss(scheme);
    case 'xml':
      return toXml(scheme);
  }
}

interface FigmaToken {
  $type: 'color';
  $value: string;
  $description: string;
  $extensions: {
    codeSyntax: string;
    codeSyntaxPlatform: 'WEB';
  };
}

function figmaRoleTokens(scheme: Scheme, mode: 'light' | 'dark'): Record<string, unknown> {
  const colors = scheme[mode];
  const tokens: Record<string, unknown> = {
    $description: `Material 3 SPEC_${scheme.requestedSpec} · ${mode} mode · seed ${scheme.seedHex} · ${scheme.styleLabel} (${scheme.variant}) · SPEC_${scheme.roleSpec} roles. Generated by m3-spec2026.`,
  };

  for (const role of ROLE_DEFS) {
    const color = colors[role.key];
    const token: FigmaToken = {
      $type: 'color',
      $value: color.hex,
      $description: `HCT ${color.hct.hue} / ${color.hct.chroma} / ${color.hct.tone}`,
      $extensions: {
        codeSyntax: `var(--md-sys-color-${role.key.replaceAll('_', '-')})`,
        codeSyntaxPlatform: 'WEB',
      },
    };
    tokens[role.key] = token;
  }

  return tokens;
}

function figmaPaletteTokens(scheme: Scheme): Record<string, unknown> {
  const document: Record<string, unknown> = {
    $description: `Material 3 SPEC_${scheme.requestedSpec} tonal palettes · seed ${scheme.seedHex} · ${scheme.styleLabel}. Generated by m3-spec2026.`,
  };

  for (const palette of scheme.palettes) {
    const group: Record<string, unknown> = {};
    for (const tone of palette.tones) {
      group[String(tone.tone)] = {
        $type: 'color',
        $value: tone.hex,
        $description: `${palette.label} tone ${tone.tone} · palette hue ${palette.hue}° · chroma ${palette.chroma}`,
      };
    }
    document[palette.key] = group;
  }

  return document;
}

/**
 * A multi-file bundle for microsoft/figma-variables-import.
 *
 * The plugin uses a small manifest to map JSON files to collection modes. Keeping
 * light and dark tokens in separate files is what makes Figma create actual
 * Light/Dark modes instead of two parallel variable sets.
 */
export function figmaBundleFiles(scheme: Scheme): Record<string, string> {
  const collection = `M3 Spec ${scheme.requestedSpec}`;
  const paletteCollection = `M3 palettes ${scheme.requestedSpec}`;
  const manifest = {
    name: `${collection} — ${scheme.seedHex}`,
    collections: {
      [collection]: {
        modes: {
          Light: ['light.tokens.json'],
          Dark: ['dark.tokens.json'],
        },
      },
      [paletteCollection]: {
        modes: {
          Tones: ['palettes.tokens.json'],
        },
      },
    },
  };

  const readme = `Material 3 SPEC_${scheme.requestedSpec} — Figma variables
=====================================

Seed: ${scheme.seedHex}${scheme.lowChromaFallback ? ` (effective ${scheme.effectiveSeedHex})` : ''}
Style: ${scheme.styleLabel} (${scheme.variant})
Role spec: SPEC_${scheme.roleSpec} (requested SPEC_${scheme.requestedSpec})
Platform: ${scheme.platform.toUpperCase()}
Contrast: ${scheme.contrast.toFixed(2)}
Generated by m3-spec2026.

Import with Microsoft's Variables Import plugin:
https://github.com/microsoft/figma-variables-import

1. Open Figma and run the Variables Import plugin.
2. Drag all four JSON files from this bundle into the plugin at once:
   - manifest.json
   - light.tokens.json
   - dark.tokens.json
   - palettes.tokens.json
3. The manifest creates:
   - "${collection}" with Light and Dark modes (67 role variables).
   - "${paletteCollection}" with a Tones mode (primary, secondary, tertiary,
     neutral, neutral-variant, and error palettes at 13 tone stops).

The collection names include the requested spec. To compare the 2021 and 2026
outputs in Figma, import each bundle into a separate Figma file: the plugin
keys variables by name, so importing both specs into one file updates the
existing variables instead of creating a parallel set.

If you import only light.tokens.json, the plugin creates a single-mode
collection instead of the Light/Dark pair.
`;

  return {
    'manifest.json': `${JSON.stringify(manifest, null, 2)}\n`,
    'light.tokens.json': `${JSON.stringify(figmaRoleTokens(scheme, 'light'), null, 2)}\n`,
    'dark.tokens.json': `${JSON.stringify(figmaRoleTokens(scheme, 'dark'), null, 2)}\n`,
    'palettes.tokens.json': `${JSON.stringify(figmaPaletteTokens(scheme), null, 2)}\n`,
    'README.txt': readme,
  };
}

export function buildFigmaBundle(scheme: Scheme): Uint8Array {
  const files = figmaBundleFiles(scheme);
  const zipped: Record<string, Uint8Array> = {};
  for (const [name, contents] of Object.entries(files)) {
    zipped[name] = strToU8(contents);
  }
  return zipSync(zipped, { level: 6 });
}


function toJson(scheme: Scheme): string {
  const roles = (map: Scheme['light']) =>
    Object.fromEntries(Object.entries(map).map(([key, value]) => [key, value.hex]));
  const hct = (map: Scheme['light']) =>
    Object.fromEntries(
      Object.entries(map).map(([key, value]) => [
        key,
        {
          hue: value.hct.hue,
          chroma: value.hct.chroma,
          tone: value.hct.tone,
        },
      ]),
    );

  return `${JSON.stringify(
    {
      generator: 'm3-spec2026',
      spec: {
        requested: `SPEC_${scheme.requestedSpec}`,
        roleSpec: `SPEC_${scheme.roleSpec}`,
        variant: scheme.variant,
        style: scheme.style,
        styleLabel: scheme.styleLabel,
        platform: scheme.platform.toUpperCase(),
        contrast: scheme.contrast,
      },
      seed: {
        hex: scheme.seedHex,
        effectiveHex: scheme.effectiveSeedHex,
        hct: scheme.seedHct,
        effectiveHct: scheme.effectiveSeedHct,
        lowChromaFallback: scheme.lowChromaFallback,
      },
      colors: {
        light: roles(scheme.light),
        dark: roles(scheme.dark),
      },
      hct: {
        light: hct(scheme.light),
        dark: hct(scheme.dark),
      },
      palettes: Object.fromEntries(
        scheme.palettes.map((palette) => [
          palette.key,
          {
            label: palette.label,
            hue: palette.hue,
            chroma: palette.chroma,
            tones: Object.fromEntries(
              palette.tones.map((tone) => [String(tone.tone), tone.hex]),
            ),
          },
        ]),
      ),
    },
    null,
    2,
  )}\n`;
}

function toKotlin(scheme: Scheme): string {
  const block = (mode: 'light' | 'dark', variable: string) => {
    const map = scheme[mode];
    const lines = ROLE_DEFS.map((role) => {
      const hex = map[role.key].hex.slice(1);
      return `    ${snakeToCamel(role.key)} = Color(0xFF${hex}),`;
    }).join('\n');
    return `val ${variable} = ColorScheme(\n${lines}\n)\n`;
  };

  return `/*
 * Material 3 color scheme — SPEC_${scheme.requestedSpec} (device-accurate)
 * Seed: ${scheme.seedHex} (HCT ${scheme.seedHct.hue}, ${scheme.seedHct.chroma}, ${scheme.seedHct.tone})
 * Style: ${scheme.styleLabel} (${scheme.variant}) · role spec: SPEC_${scheme.roleSpec}
 * Platform: ${scheme.platform.toUpperCase()} · contrast: ${scheme.contrast.toFixed(1)}
 *
 * Generated by m3-spec2026. This mirrors the role set emitted by Android's
 * ThemePicker / SystemUI monet ColorScheme.
 */

// Light
${block('light', 'lightColorScheme')}
// Dark
${block('dark', 'darkColorScheme')}`;
}

function cssVariableName(role: string): string {
  return `--md-sys-color-${role.replaceAll('_', '-')}`;
}

function cssBlock(map: Scheme['light'], indent = '  '): string {
  return Object.entries(map)
    .map(([role, color]) => `${indent}${cssVariableName(role)}: ${color.hex};`)
    .join('\n');
}

function toCss(scheme: Scheme): string {
  return `/*
 * Material 3 · SPEC_${scheme.requestedSpec}
 * Seed: ${scheme.seedHex} · ${scheme.styleLabel} · ${scheme.platform.toUpperCase()} · contrast ${scheme.contrast.toFixed(1)}
 * Generated by m3-spec2026
 */

:root {
  color-scheme: light;
${cssBlock(scheme.light)}
}

[data-theme="dark"] {
  color-scheme: dark;
${cssBlock(scheme.dark)}
}

/* Optional: follow the OS when no explicit theme is set. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${cssBlock(scheme.dark, '    ')}
  }
}
`;
}

function toXml(scheme: Scheme): string {
  const light = ROLE_DEFS.map(
    (role) =>
      `    <color name="system_${role.key}">#ff${scheme.light[role.key].hex.slice(1)}</color>`,
  ).join('\n');
  const dark = ROLE_DEFS.map(
    (role) =>
      `    <color name="system_${role.key}_dark">#ff${scheme.dark[role.key].hex.slice(1)}</color>`,
  ).join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  Material 3 · SPEC_${scheme.requestedSpec}
  Seed: ${scheme.seedHex} · ${scheme.styleLabel} · ${scheme.platform.toUpperCase()} · contrast ${scheme.contrast.toFixed(1)}
  Base values are light; _dark values are provided for night mode.
  Generated by m3-spec2026
-->
<resources>
${light}

${dark}
</resources>
`;
}
